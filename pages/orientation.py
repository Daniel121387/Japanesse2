# (히라가나, 가타카나, 소리) — 글자 수와 소리 개수가 같다
GOJUON = [
    ("あいうえお", "アイウエオ", "아 이 우 에 오"),
    ("かきくけこ", "カキクケコ", "카 키 쿠 케 코"),
    ("さしすせそ", "サシスセソ", "사 시 스 세 소"),
    ("たちつてと", "タチツテト", "타 치 츠 테 토"),
    ("なにぬねの", "ナニヌネノ", "나 니 누 네 노"),
    ("はひふへほ", "ハヒフヘホ", "하 히 후 헤 호"),
    ("まみむめも", "マミムメモ", "마 미 무 메 모"),
    ("やゆよ", "ヤユヨ", "야 유 요"),
    ("らりるれろ", "ラリルレロ", "라 리 루 레 로"),
    ("わを", "ワヲ", "와 오"),
    ("ん", "ン", "응(받침)"),
]


def _table(kana_index: int) -> pd.DataFrame:
    rows = [
        " · ".join(f"{kana} {sound}" for kana, sound in zip(row[kana_index], row[2].split()))
        for row in GOJUON
    ]
    return pd.DataFrame({"글자 · 소리": rows})


